package serie04;

public class Unicode {
    public static void main(String[] args) {
        char etoile = '*';
        char neuf = '9';
        char w = 'W';
        System.out.println("Unicode de * " + (int) etoile);
        System.out.println("Unicode de 9 " + (int) neuf);
        System.out.println("Unicode de W " + (int) w);
        System.out.println("Caractere correspondant a l'Unicode 34 " + (char) 34);
        System.out.println("Caractere correspondant a l'Unicode 65 " + (char) 65);
        System.out.println("Caractere correspondant a l'Unicode 123 " + (char) 123);
    }
}
